#!/usr/bin/env python3
"""Generate src/generated/keysym_ucs.inc: the Unicode character of every
keysym that has one, from the "U+XXXX" comments of X11/keysymdef.h (MIT).

usage: tools/gen_keysym_ucs.py   (from the repository root)
"""
import os, re

repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(repo, "include", "X11", "keysymdef.h")).read()
pairs = {}
for m in re.finditer(r"^#define XK_\w+\s+0x([0-9a-fA-F]+)\s*/\*\s*U\+([0-9A-Fa-f]{4,6})\b", src, re.M):
    ks, ucs = int(m.group(1), 16), int(m.group(2), 16)
    # keysyms below 0x100 are Latin-1 already, and 0x01xxxxxx are Unicode
    if 0x100 <= ks < 0x01000000 and ks not in pairs:
        pairs[ks] = ucs
with open(os.path.join(repo, "src", "generated", "keysym_ucs.inc"), "w") as f:
    f.write("// Generated by tools/gen_keysym_ucs.py from X11/keysymdef.h (MIT). Do not edit.\n")
    for ks in sorted(pairs):
        f.write("{ 0x%04x, 0x%04x },\n" % (ks, pairs[ks]))
print("keysyms with a character:", len(pairs))
